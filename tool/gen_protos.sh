#!/usr/bin/env bash
# Regenerates the Dart protobuf bindings in lib/src/proto/ from a checkout of
# https://github.com/fishjam-cloud/protos.
#
# Usage: tool/gen_protos.sh <path-to-protos-checkout>
#
# Minimum compatible protos revision: 50aacf9 (v0.29.0). Any later revision
# without peer-facing changes works as well.
#
# Tools: protoc is pinned in mise.toml; protoc-gen-dart comes from the
# protoc_plugin dev dependency pinned in pubspec.lock.
set -euo pipefail

if [[ $# -ne 1 ]]; then
  echo "usage: $0 <path-to-protos-checkout>" >&2
  exit 64
fi

PROTOS_DIR="$(cd "$1" && pwd)"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/lib/src/proto"

FILES=(
  fishjam/peer_notifications.proto
  fishjam/media_events/shared.proto
  fishjam/media_events/peer/peer.proto
  fishjam/media_events/server/server.proto
)

for f in "${FILES[@]}"; do
  if [[ ! -f "$PROTOS_DIR/$f" ]]; then
    echo "missing $PROTOS_DIR/$f" >&2
    exit 66
  fi
done

PLUGIN_DIR="$(mktemp -d)"
trap 'rm -rf "$PLUGIN_DIR"' EXIT
cat > "$PLUGIN_DIR/protoc-gen-dart" <<WRAPPER
#!/usr/bin/env bash
cd "$ROOT" && exec dart run protoc_plugin:protoc_plugin "\$@"
WRAPPER
chmod +x "$PLUGIN_DIR/protoc-gen-dart"

rm -rf "$OUT"
mkdir -p "$OUT"

protoc \
  --plugin=protoc-gen-dart="$PLUGIN_DIR/protoc-gen-dart" \
  --dart_out="$OUT" \
  -I "$PROTOS_DIR" \
  "${FILES[@]}"

REV="$(git -C "$PROTOS_DIR" rev-parse --short HEAD 2>/dev/null || echo unknown)"
cat > "$OUT/README.md" <<README
Generated by \`tool/gen_protos.sh\` from fishjam-cloud/protos @ $REV. Do not edit by hand.
README

dart format "$OUT" >/dev/null
echo "generated $(find "$OUT" -name '*.dart' | wc -l | tr -d ' ') files into lib/src/proto (protos @ $REV)"
